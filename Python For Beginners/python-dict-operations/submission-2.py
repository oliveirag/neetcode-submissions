your_dict = { 
  "a": 10, 
  "apple": 12,
  "bat": 7
}

print(your_dict) # print dictionary
print(your_dict["a"]) # print the value of key "a"
print("d" in your_dict) # print true or false whether the key "d" is in the dictionary
your_dict["a"] = 4 # reassign the value of the key "a" to 4
print(your_dict) # print dictionary again
